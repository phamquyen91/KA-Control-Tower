export const DAILY_FC: DailyFcRow[] = DAILY_FC_RAW.map(
  ([date, scope, band, value]) => ({ date, scope, band, value }),
);

/**
 * Tổng FC của một tháng, tính đến hết ngày `through` (dạng "YYYY-MM-DD").
 *
 * Trả về undefined khi tháng đó không có FC theo ngày, để chỗ gọi bỏ trống thay
 * vì hiểu nhầm thành 0.
 */
export function fcThrough(
  scope: DataScope,
  month: string,
  through: string,
  band?: WeightBand,
): number | undefined {
  const rows = DAILY_FC.filter(
    (r) =>
      r.scope === scope &&
      r.date.startsWith(month) &&
      r.date <= through &&
      (band ? r.band === band : true),
  );
  return rows.length
    ? rows.reduce((acc, r) => acc + r.value, 0)
    : undefined;
}

/**
 * FC của MỘT ngày (tổng các band). Dùng cho ngày campaign: CP 9.9 → 09/09 (D)
 * và 10/09 (D+1). undefined khi ngày đó không có trong file forecast — giao
 * diện bỏ trống chứ không lấy tháng chia đều.
 */
export function dailyFcFor(scope: DataScope, date: string): number | undefined {
  const rows = DAILY_FC.filter((r) => r.scope === scope && r.date === date);
  if (rows.length === 0) return undefined;
  // Có dòng "total" thì lấy nó; không thì cộng các band.
  const total = rows.find((r) => r.band === "total");
  return total
    ? total.value
    : rows.reduce((acc, r) => acc + r.value, 0);
}
